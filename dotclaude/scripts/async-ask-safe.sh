#!/bin/bash
# Async Full Research Script with Direct Output Capture
# Saves comprehensive Q&A to questions folder with descriptive filenames

# Get the raw question
QUESTION="$1"

# Generate timestamp
TIMESTAMP=$(date +%Y-%m-%d__%H-%M-%S)

# Escape question for safe shell usage
ESCAPED_QUESTION=$(printf '%s' "$QUESTION" | sed "s/'/'\\\\''/g")

# Generate topic summary from question (sanitized, max 30 chars)
TOPIC=$(echo "$QUESTION" | \
  sed 's/[^a-zA-Z0-9 ]//g' | \
  head -c 30 | \
  sed 's/ *$//' | \
  tr ' ' '-' | \
  tr '[:upper:]' '[:lower:]')

# Determine save location with proper directory creation
STARTING_DIR=$(pwd)
if [ -d "./private/claude" ]; then
    # ./private/claude exists, use it
    QUESTIONS_DIR="$(pwd)/private/claude/questions"
    LOCATION="project"
elif [ -d "./private" ]; then
    # ./private exists but not ./private/claude, create it
    QUESTIONS_DIR="$(pwd)/private/claude/questions"
    LOCATION="project"
else  
    # No ./private directory, use global location
    QUESTIONS_DIR="$HOME/claude/questions"
    LOCATION="global"
fi
# Create the full path including any missing parent directories
mkdir -p "$QUESTIONS_DIR"

# Create descriptive filename for full research
FILENAME="${TIMESTAMP}__fullqa__${TOPIC}.md"
FULL_PATH="$QUESTIONS_DIR/$FILENAME"

# Generate file URL early for display
if [[ "$OSTYPE" == "msys" ]] || [[ "$OSTYPE" == "cygwin" ]] || [[ "$OSTYPE" == "win32" ]]; then
    # Windows: convert the POSIX /<drive>/ path form to the native <drive>:/ form
    FILE_URL=$(echo "$QUESTIONS_DIR/$FILENAME" | sed 's|^/\([a-z]\)/|\1:/|')
    FILE_URL="file:///$FILE_URL"
else
    # Unix/Linux/Mac: Use path as-is
    FILE_URL="file://$QUESTIONS_DIR/$FILENAME"
fi

# Compact notification for 4-line preview with clickable link FIRST
echo "📄 $FILE_URL"
echo "🔬 Full Research starting..."
echo "⏱️ Expected: 2-5 minutes"

# Run the actual research in subprocess
{
    START_TIME=$SECONDS
    
    # Change to questions directory to prevent session pollution
    cd "$QUESTIONS_DIR"
    
    # Capture full output from claude subprocess with WebSearch access
    echo "🔄 Running full research agent (this may take 2-5 minutes)..."
    FULL_OUTPUT=$(printf '/longask %s\n' "$ESCAPED_QUESTION" | claude -p --allowedTools "Task,WebSearch,WebFetch,Read,Grep,Glob,Write" 2>&1)
    
    # Calculate duration
    DURATION=$((SECONDS - START_TIME))
    DURATION_MIN=$((DURATION / 60))
    DURATION_SEC=$((DURATION % 60))
    
    # Extract the research answer (more complex for full research)
    # Try multiple patterns since longask output varies
    ANSWER=$(echo "$FULL_OUTPUT" | sed -n '/^## /,/^---$/p' | sed '$d')
    
    # If no structured answer, try to extract from response
    if [ -z "$ANSWER" ] || [ $(echo "$ANSWER" | wc -l) -lt 5 ]; then
        # Look for the main content between common markers
        ANSWER=$(echo "$FULL_OUTPUT" | sed -n '/Answer:/,$p')
    fi
    
    # If still minimal, use fuller output
    if [ -z "$ANSWER" ] || [ $(echo "$ANSWER" | wc -l) -lt 5 ]; then
        ANSWER="$FULL_OUTPUT"
    fi
    
    # Create comprehensive Q&A document
    cat > "$FULL_PATH" <<EOF
# Research Q&A: ${QUESTION}

**Date**: $TIMESTAMP  
**Type**: Full Research (Async)  
**Duration**: ${DURATION_MIN} minutes ${DURATION_SEC} seconds  
**Method**: claude -p with help agent (comprehensive mode)  

## Question

$QUESTION

## Research Answer

$ANSWER

## Research Metadata

- **Topic Tag**: ${TOPIC}
- **Session Location**: $(pwd)
- **Script**: async-ask-safe.sh
- **Agent**: help (via /longask)
- **Research Mode**: Full comprehensive with web search capabilities
- **Starting Directory**: $STARTING_DIR

---
*Generated by async full research system - Comprehensive research in isolated subprocess*
EOF
    
    # Extract first substantive line of answer for summary
    SUMMARY=$(echo "$ANSWER" | grep -v '^#' | grep -v '^$' | grep -v '^**' | head -n 1 | cut -c 1-100)
    if [ -z "$SUMMARY" ]; then
        SUMMARY="Research completed successfully"
    fi
    
    # Completion notification
    echo "✅ FULL RESEARCH READY! (${DURATION_MIN}m ${DURATION_SEC}s)"
    echo "💡 $SUMMARY..."
    echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
}