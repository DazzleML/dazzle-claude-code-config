#!/bin/bash
# Async Quick Q&A Script with Direct Output Capture
# Saves Q&A directly to questions folder with descriptive filenames

# Get the raw question
QUESTION="$1"

# Generate timestamp
TIMESTAMP=$(date +%Y-%m-%d__%H-%M-%S)

# Escape question for safe shell usage
ESCAPED_QUESTION=$(printf '%s' "$QUESTION" | sed "s/'/'\\\\''/g")

# Generate topic summary from question (sanitized, max 30 chars)
TOPIC=$(echo "$QUESTION" | \
  sed 's/[^a-zA-Z0-9 ]//g' | \
  head -c 30 | \
  sed 's/ *$//' | \
  tr ' ' '-' | \
  tr '[:upper:]' '[:lower:]')

# Determine save location with proper directory creation
STARTING_DIR=$(pwd)
if [ -d "./private/claude" ]; then
    # ./private/claude exists, use it
    QUESTIONS_DIR="$(pwd)/private/claude/questions"
    LOCATION="project"
elif [ -d "./private" ]; then
    # ./private exists but not ./private/claude, create it
    QUESTIONS_DIR="$(pwd)/private/claude/questions"
    LOCATION="project"
else  
    # No ./private directory, use global location
    QUESTIONS_DIR="$HOME/claude/questions"
    LOCATION="global"
fi
# Create the full path including any missing parent directories
mkdir -p "$QUESTIONS_DIR"

# Create descriptive filename
FILENAME="${TIMESTAMP}__quickqa__${TOPIC}.md"
FULL_PATH="$QUESTIONS_DIR/$FILENAME"

# Generate file URL early for display
if [[ "$OSTYPE" == "msys" ]] || [[ "$OSTYPE" == "cygwin" ]] || [[ "$OSTYPE" == "win32" ]]; then
    # Windows: convert the POSIX /<drive>/ path form to the native <drive>:/ form
    FILE_URL=$(echo "$QUESTIONS_DIR/$FILENAME" | sed 's|^/\([a-z]\)/|\1:/|')
    FILE_URL="file:///$FILE_URL"
else
    # Unix/Linux/Mac: Use path as-is
    FILE_URL="file://$QUESTIONS_DIR/$FILENAME"
fi

# Compact notification for 4-line preview with clickable link FIRST
echo "📄 $FILE_URL"
echo "🚀 Quick Q&A starting..."

# Run the actual quick-ask command in subprocess
{
    START_TIME=$SECONDS
    
    # Change to questions directory to prevent session pollution
    cd "$QUESTIONS_DIR"
    
    # Capture full output from claude subprocess with WebSearch access
    echo "🔄 Running quick-ask agent..."
    FULL_OUTPUT=$(printf '/quick-ask %s\n' "$ESCAPED_QUESTION" | claude -p --allowedTools "Task,WebSearch,WebFetch,Read,Grep,Glob" 2>&1)
    
    # Calculate duration
    DURATION=$((SECONDS - START_TIME))
    
    # Extract the answer portion (between ## and ---)
    # First try to extract a clean answer
    ANSWER=$(echo "$FULL_OUTPUT" | sed -n '/^## /,/^---$/p' | sed '$d')
    
    # If no structured answer found, try alternate patterns
    if [ -z "$ANSWER" ]; then
        ANSWER=$(echo "$FULL_OUTPUT" | sed -n '/Answer:/,/^$/p')
    fi
    
    # If still no answer, use full output
    if [ -z "$ANSWER" ]; then
        ANSWER="$FULL_OUTPUT"
    fi
    
    # Create the Q&A document with proper formatting
    cat > "$FULL_PATH" <<EOF
# Q&A: ${QUESTION}

**Date**: $TIMESTAMP  
**Type**: Quick Q&A (Async)  
**Duration**: ${DURATION} seconds  
**Method**: claude -p with help agent  

## Question

$QUESTION

## Answer

$ANSWER

## Metadata

- **Topic Tag**: ${TOPIC}
- **Session Location**: $(pwd)
- **Script**: async-quick-safe.sh
- **Agent**: help (via /quick-ask)

---
*Generated by async Q&A system - Question answered in isolated subprocess*
EOF
    
    # Extract first substantive line of answer for summary
    SUMMARY=$(echo "$ANSWER" | grep -v '^#' | grep -v '^$' | grep -v '^**' | head -n 1 | cut -c 1-100)
    if [ -z "$SUMMARY" ]; then
        SUMMARY="Answer saved successfully"
    fi
    
    # Completion notification
    echo "✅ QUICK ANSWER READY! (${DURATION}s)"
    echo "💡 $SUMMARY..."
    echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
}